#!/usr/bin/env python3
"""Builds compliance/geoblock.json from the research input and the ISO 3166-1 table. UNAUDITED prototype tooling;
stdlib only; deterministic output (sorted keys, fixed formatting).

    python3 -I compliance/tools/build_geoblock.py           # writes compliance/geoblock.json
    python3 -I compliance/tools/build_geoblock.py --check   # exit 1 if the committed file differs from a build

Inputs: compliance/research/jurisdictions.json (curated, every entry with source ids),
compliance/research/sources.json, compliance/research/iso3166.tab (tz database 2026f, public domain) and the
previous list compliance/research/geoblock-0.1.1.json (354), whose rule, tiers, anonymizers and denied_policy are
carried over unchanged and whose entries may only stay as strict or become stricter (tests).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, "research")
OUT = os.path.join(ROOT, "geoblock.json")
OUT_MD = os.path.join(ROOT, "jurisdictions.md")
STRICTNESS = {"allowed": 0, "restricted-review": 1, "blocked": 2}
REASONS_ADDED = ["sanctions-crypto-services-prohibition", "residual-sanctions", "fatf-call-for-action"]


def load(name):
    with open(os.path.join(RES, name), encoding="utf8") as f:
        return json.load(f)


def iso_codes():
    out = {}
    with open(os.path.join(RES, "iso3166.tab"), encoding="utf8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            code, name = line.rstrip("\n").split("\t")
            out[code] = name
    return out


def entry(name, src):
    e = {"name": name, "tier": src["tier"], "reasons": list(src["reasons"]), "sources": list(src.get("sources", [])),
         "confidence": src.get("confidence", "none"), "researched": bool(src.get("sources"))}
    if src.get("counsel"):
        e["counsel"] = list(src["counsel"])
    if src.get("note"):
        e["note"] = src["note"]
    return e


def build():
    base = load("geoblock-0.1.1.json")
    res = load("jurisdictions.json")
    iso = iso_codes()
    countries = {}
    for code, name in iso.items():
        countries[code] = {"name": name, "tier": "restricted-review", "reasons": ["not-researched"], "sources": [],
                           "confidence": "none", "researched": False}
    for g in res["groups"].values():
        for code in g["codes"]:
            if code not in iso:
                raise SystemExit(f"group code {code} not in ISO table")
            countries[code] = entry(iso[code], g)
    for code, src in res["countries"].items():
        if code not in iso:
            raise SystemExit(f"country code {code} not in ISO table")
        name = base["countries"].get(code, {}).get("name", iso[code])
        countries[code] = entry(name, src)
    subs = {code: entry(src["name"], src) for code, src in res["subdivisions"].items()}
    out = {
        "schema": base["schema"],
        "version": "0.2.0",
        "generated_utc": res["date"],
        "status": ("DRAFT FOR COUNSEL. UNAUDITED prototype. Not legal advice. v0.2: every ISO 3166-1 code listed; "
                   "researched entries carry source ids (compliance/research/sources.json, exact sentences); every "
                   "unresearched code is restricted-review (denied); no country is allowed until counsel decides (Q-2)."),
        "rule": base["rule"],
        "tiers": base["tiers"],
        "default_tier": base["default_tier"],
        "unknown_country_effect": base["unknown_country_effect"],
        "reason_categories": base["reason_categories"] + [r for r in REASONS_ADDED if r not in base["reason_categories"]],
        "sources_file": "compliance/research/sources.json",
        "iso3166_source": "S-ISO3166-TZDATA",
        "countries": dict(sorted(countries.items())),
        "subdivisions": dict(sorted(subs.items())),
        "anonymizers": base["anonymizers"],
        "denied_policy": base["denied_policy"],
        "counsel_questions": res["counsel_questions"],
    }
    return json.dumps(out, indent=2, ensure_ascii=False) + "\n"


def render_md(text):
    geo = json.loads(text)
    src = {x["id"]: x for x in load("sources.json")["sources"]}
    tiers = {}
    for e in geo["countries"].values():
        tiers[e["tier"]] = tiers.get(e["tier"], 0) + 1
    lines = [
        "# PosternDEX Perpetuals: jurisdiction research (generated from geoblock.json %s)" % geo["version"], "",
        "DRAFT FOR COUNSEL. UNAUDITED prototype. Not legal advice. Generated by `compliance/tools/build_geoblock.py`;",
        "do not edit by hand (edit `compliance/research/jurisdictions.json`). Exact sentences relied on are in",
        "`compliance/research/sources.json`.", "",
        "Rule (unchanged from 0.1.1): deny by default; only tier `allowed` opens a country; 0.2 has no `allowed` entry.", "",
        "Counts over the %d ISO 3166-1 codes: %s." % (len(geo["countries"]), ", ".join(
            "%s %d" % (k, tiers[k]) for k in sorted(tiers))), "",
        "## Researched entries", "",
        "| Code | Name | Tier | Reasons | Sources | Confidence | Counsel | Note |",
        "|---|---|---|---|---|---|---|---|",
    ]
    rows = [(c, e) for c, e in geo["countries"].items() if e["researched"] or e.get("counsel")]
    rows += [(c, e) for c, e in geo["subdivisions"].items()]
    for c, e in rows:
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            c, e["name"], e["tier"], ", ".join(e["reasons"]), ", ".join(e["sources"]) or "none",
            e["confidence"], ", ".join(e.get("counsel", [])) or "", e.get("note", "").replace("|", "/")))
    lines += ["", "## Sources", ""]
    used = sorted({s for _, e in rows for s in e["sources"]})
    for s in used:
        x = src[s]
        lines.append("- %s: %s, \"%s\", %s (read %s)%s" % (s, x["publisher"], x["title"], x["url"], x["read_utc"],
                     "; " + x["status"] if x.get("status") else ""))
    lines += ["", "## Questions for counsel", ""]
    for q, t in geo["counsel_questions"].items():
        lines.append("- %s: %s" % (q, t))
    lines += ["", "## Not done / not proven", "",
              "- %d codes are `restricted-review` / `not-researched`: denied, never researched." % sum(
                  1 for e in geo["countries"].values() if not e["researched"]),
              "- Sources marked UNVERIFIED or SECONDARY were not read in primary text; they only keep entries closed.",
              "- No legal conclusion is drawn anywhere: every tier is a proposal for counsel.", ""]
    return "\n".join(lines)


def main(argv):
    text = build()
    md = render_md(text)
    if "--check" in argv:
        with open(OUT, encoding="utf8") as f:
            same = f.read() == text
        with open(OUT_MD, encoding="utf8") as f:
            same_md = f.read() == md
        print("geoblock.json and jurisdictions.md are the build output" if same and same_md else "DIFFERS from the build")
        return 0 if same and same_md else 1
    with open(OUT, "w", encoding="utf8") as f:
        f.write(text)
    with open(OUT_MD, "w", encoding="utf8") as f:
        f.write(md)
    print(f"wrote {OUT} and {OUT_MD}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
