#!/usr/bin/env node
// Generates config/markets.json (the market table this interface signs against) from compliance/markets.json.
// UNAUDITED prototype. Never edit config/markets.json by hand.
//
//   node scripts/pin-markets.mjs            write the pin
//   node scripts/pin-markets.mjs --check    exit 1 when the committed pin differs from what would be generated
//
// When the SIGNING fields of a market change (marketId, base, priceDecimals, sizeDecimals, tick, step) the script
// says so in capitals: that is a change of what a signature means and needs a review, not only a new pin.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(resolve(frontend, '../compliance/markets.json'), 'utf8'));
const path = resolve(frontend, 'config/markets.json');
const fraction = (ppm) => {
  const s = (BigInt(ppm) + 1_000_000n).toString().slice(1); // six places, exact
  const whole = BigInt(ppm) / 1_000_000n;
  const frac = s.replace(/0+$/, '');
  return frac ? `${whole}.${frac}` : `${whole}`;
};
const pin = {
  note: 'UNAUDITED prototype. The market table this interface signs against, PINNED: symbol, marketId, base, decimals, tick and step. The interface refuses to sign when GET /v1/markets publishes a different value for any of these fields (src/lib/pins.ts). Generated by scripts/pin-markets.mjs from compliance/markets.json (version below); src/test/pins-compliance.test.ts fails when the two differ in a signing field. The other fields (sizes, leverage, tiers) are the exchange\'s to publish and are here only as the fixture of the tests.',
  source: `compliance/markets.json ${source.version}`,
  markets: source.markets.map((m) => ({
    symbol: m.symbol,
    marketId: m.marketId,
    base: m.base,
    priceDecimals: m.priceDecimals,
    sizeDecimals: m.sizeDecimals,
    tickSize: m.tick,
    stepSize: m.step,
    minOrderSize: m.minSize,
    maxOrderSize: m.maxSize,
    maxLeverage: String(m.maxLeverage),
    marginTiers: m.tiers.map((t) => ({
      notionalFloor: t.floor,
      initialMarginFraction: fraction(t.imfPpm),
      maintenanceMarginFraction: fraction(t.mmfPpm),
      maxLeverage: String(Math.floor(1_000_000 / t.imfPpm)),
    })),
  })),
};
const text = `${JSON.stringify(pin, null, 2)}\n`;
let before = null;
try {
  before = JSON.parse(readFileSync(path, 'utf8'));
} catch {
  before = null;
}
const SIGNING = ['marketId', 'base', 'priceDecimals', 'sizeDecimals', 'tickSize', 'stepSize'];
const signing = (table) => JSON.stringify((table?.markets ?? []).map((m) => [m.symbol, ...SIGNING.map((f) => m[f])]));
const signingChanged = before !== null && signing(before) !== signing(pin);
if (process.argv.includes('--check')) {
  const same = before !== null && `${JSON.stringify(before, null, 2)}\n` === text;
  console.log(same ? 'market pin: equal to compliance/markets.json' : `market pin: DIFFERS from compliance/markets.json${signingChanged ? ' IN A SIGNING FIELD' : ' (no signing field)'}`);
  process.exit(same ? 0 : 1);
}
writeFileSync(path, text);
console.log(`pinned ${pin.markets.length} markets from ${pin.source}; signing fields ${before === null ? 'new' : signingChanged ? 'CHANGED: REVIEW WHAT A SIGNATURE MEANS' : 'unchanged'}`);
