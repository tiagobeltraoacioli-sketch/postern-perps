#!/usr/bin/env node
// Writes <dist>/_headers (Cloudflare Pages / Netlify format) with the site's security headers. UNAUDITED prototype.
// CSP: scripts and fonts only from this origin; connect-src only this origin plus the API, WebSocket and L2 RPC
// origins of the committed config (config/production.json). No third-party origin of any kind.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dist = process.argv[2];
if (!dist) {
  console.error('usage: write-headers.mjs <dist>');
  process.exit(2);
}
const config = JSON.parse(readFileSync(new URL('../config/production.json', import.meta.url), 'utf8'));
const origins = [...new Set([config.apiUrl, config.wsUrl, config.l2RpcUrl].map((u) => new URL(u).origin))];
export const csp = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data:",
  `connect-src 'self' ${origins.join(' ')}`,
  "manifest-src 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  'upgrade-insecure-requests',
].join('; ');
const text = `# Generated by scripts/write-headers.mjs from config/production.json.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=63072000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=(), hid=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
/index.html
  Cache-Control: no-cache
/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
writeFileSync(join(dist, '_headers'), text);
console.log(`_headers written: connect-src ${origins.join(' ')}`);
